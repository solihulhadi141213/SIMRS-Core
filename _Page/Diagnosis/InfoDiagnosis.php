<div class="mb-4">
    <b class="text-secondary">
        1. Admission
    </b>
    <p class="mb-0 mt-1">
        Diagnosis awal yang dicatat saat pasien pertama kali masuk atau diterima untuk mendapatkan pelayanan kesehatan. Diagnosis ini biasanya dibuat berdasarkan keluhan utama pasien dan hasil pemeriksaan awal sehingga masih bersifat sementara serta dapat berubah setelah pemeriksaan lebih lanjut dilakukan.
    </p>
</div>

<div class="mb-4">
    <b class="text-secondary">
        2. Provisional
    </b>
    <p class="mb-0 mt-1">
        Diagnosis sementara yang dibuat berdasarkan anamnesis, pemeriksaan fisik, atau pemeriksaan awal sebelum diagnosis pasti ditegakkan. Diagnosis ini digunakan sebagai dugaan awal dokter dan masih memerlukan pemeriksaan penunjang atau evaluasi lanjutan.
    </p>
</div>

<div class="mb-4">
    <b class="text-secondary">
        3. Primary
    </b>
    <p class="mb-0 mt-1">
        Diagnosis utama yang menjadi penyebab utama pasien mendapatkan pelayanan atau perawatan medis. Diagnosis ini menjadi fokus utama terapi, tindakan medis, pelaporan, dan proses klaim pelayanan kesehatan.
    </p>
</div>

<div class="mb-4">
    <b class="text-secondary">
        4. Secondary
    </b>
    <p class="mb-0 mt-1">
        Diagnosis tambahan yang menyertai diagnosis utama dan dapat mempengaruhi kondisi pasien, proses pelayanan, maupun hasil perawatan. Diagnosis sekunder dapat berupa penyakit penyerta, komplikasi, atau kondisi lain yang relevan secara klinis.
    </p>
</div>

<div class="mb-4">
    <b class="text-secondary">
        5. Working
    </b>
    <p class="mb-0 mt-1">
        Diagnosis kerja yang digunakan dokter sebagai dasar sementara dalam menentukan tindakan medis selama proses evaluasi berlangsung. Diagnosis ini dapat berubah sesuai perkembangan kondisi pasien dan hasil pemeriksaan tambahan.
    </p>
</div>

<div class="mb-4">
    <b class="text-secondary">
        6. Differential
    </b>
    <p class="mb-0 mt-1">
        Diagnosis banding yang berisi beberapa kemungkinan penyakit lain dengan gejala yang mirip sehingga perlu dipertimbangkan sebelum menetapkan diagnosis pasti. Diagnosis ini membantu proses analisis dan pengambilan keputusan klinis oleh dokter.
    </p>
</div>

<div class="mb-2">
    <b class="text-secondary">
        7. Final
    </b>
    <p class="mb-0 mt-1">
        Diagnosis akhir atau diagnosis pasti yang telah ditegakkan berdasarkan hasil pemeriksaan lengkap, evaluasi medis, dan pertimbangan klinis dokter. Diagnosis ini menjadi kesimpulan resmi kondisi pasien pada episode pelayanan tersebut.
    </p>
</div>